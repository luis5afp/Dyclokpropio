# diloakPRO migration. User-scope only; no profile-data deletion.
# Runs after new app is installed, but before the new desktop shortcuts are set.
[CmdletBinding()]
param([string]$CurrentInstall="",[switch]$InventoryOnly)
$ErrorActionPreference='Stop'
$legacy=@(
 @{Name='DICloak Almacén Lab';Dir='DICloak-Nativo-Almacen-Lab-030';Shortcut='DICloak Almacén Lab'}
 @{Name='DICloak Almacén Lab 0.3.1';Dir='DICloak-Nativo-Almacen-Lab-031';Shortcut='DICloak Almacén Lab 0.3.1'}
 @{Name='DICloak Almacén Lab 0.3.2';Dir='DICloak-Nativo-Almacen-Lab-032';Shortcut='DICloak Almacén Lab 0.3.2'}
 @{Name='DICloak Almacén Lab 0.3.3';Dir='DICloak-Nativo-Almacen-Lab-033';Shortcut='DICloak Almacén Lab 0.3.3'}
 @{Name='DICloak Almacén Audit 0.3.4';Dir='DICloak-Nativo-Almacen-Audit-034';Shortcut='DICloak Almacén Audit 0.3.4'}
 @{Name='DICloak Almacén Diagnóstico 0.3.9';Dir='DICloak-Nativo-Almacen-Diagnostico-039';Shortcut='DICloak Almacén Diagnóstico 0.3.9'}
 @{Name='DICloak Almacén Diagnóstico Etapas 0.4.0';Dir='DICloak-Nativo-Almacen-Diagnostico-Etapas-040';Shortcut='DICloak Almacén Diagnóstico Etapas 0.4.0'}
 @{Name='DICloak Almacén Diagnóstico Legible 0.4.1';Dir='DICloak-Nativo-Almacen-Diagnostico-Legible-041';Shortcut='DICloak Almacén Diagnóstico Legible 0.4.1'}
 @{Name='Dyclokpropio Motor 0.4.2 Diagnóstico 30.0.15';Dir='Dyclokpropio-Motor-042-Diagnostico-3015';Shortcut='Dyclokpropio Motor 0.4.2 Diagnóstico 30.0.15'}
)
if($InventoryOnly){
 $legacy | ForEach-Object { Write-Output ($_.Name+' | '+$_.Dir) }
 exit 0
}
$programs=[IO.Path]::GetFullPath((Join-Path $env:LOCALAPPDATA 'Programs'))
$newInstall=[IO.Path]::GetFullPath((Join-Path $programs 'diloakPRO'))
if($CurrentInstall){
 try{$newInstall=[IO.Path]::GetFullPath($CurrentInstall)}catch{exit 3}
}
$regRoot='HKCU:\Software\Microsoft\Windows\CurrentVersion\Uninstall'
$installed=@(Get-ItemProperty -Path "$regRoot\*" -ErrorAction SilentlyContinue)
$desktop=[Environment]::GetFolderPath('Desktop')
$startPrograms=[Environment]::GetFolderPath('Programs')
$summary=@()
$problems=0
function Remove-VerifiedShortcut([string]$link,[string]$target){
 if(-not(Test-Path -LiteralPath $link -PathType Leaf)){return}
 try{
   $shell=New-Object -ComObject WScript.Shell
   $actual=$shell.CreateShortcut($link).TargetPath
   if([string]::Equals([IO.Path]::GetFullPath($actual),[IO.Path]::GetFullPath($target),
     [StringComparison]::OrdinalIgnoreCase)){
       Remove-Item -LiteralPath $link -Force
   }
 }catch{
   # Never remove unknown or uninspectable shortcuts.
 }
}
foreach($entry in $legacy){
 $folder=[IO.Path]::GetFullPath((Join-Path $programs $entry.Dir))
 if([string]::Equals($folder,$newInstall,[StringComparison]::OrdinalIgnoreCase)){continue}
 if(-not(Test-Path -LiteralPath $folder -PathType Container)){continue}
 $regEntries=@($installed | Where-Object {
   $_.DisplayName -eq $entry.Name -or
   ($_.DisplayName -is [string] -and $_.DisplayName.StartsWith($entry.Name+' ',[StringComparison]::OrdinalIgnoreCase))
 })
 if($regEntries.Count -ne 1){
   $summary += @{product=$entry.Name;result='manual-uninstall-required';reason='registry-entry-not-unique'}
   $problems++;continue
 }
 $uninstallers=@(Get-ChildItem -LiteralPath $folder -Filter 'Uninstall*.exe' -File -ErrorAction SilentlyContinue)
 if($uninstallers.Count -ne 1){
   $summary += @{product=$entry.Name;result='manual-uninstall-required';reason='uninstaller-not-unique'}
   $problems++;continue
 }
 $uninstall=$uninstallers[0].FullName
 $registered=[string]$regEntries[0].UninstallString
 $matches=$registered.StartsWith('"'+$uninstall+'"',[StringComparison]::OrdinalIgnoreCase) -or
   $registered.StartsWith($uninstall+' ',[StringComparison]::OrdinalIgnoreCase)
 if(-not$matches -or -not(Test-Path -LiteralPath (Join-Path $folder 'DICloak.exe') -PathType Leaf)){
   $summary += @{product=$entry.Name;result='manual-uninstall-required';reason='uninstaller-verification-failed'}
   $problems++;continue
 }
 try{
   # Only invoke the uninstaller generated by a verified old lab installation.
   # It is never an arbitrary supplied script or executable.
   $proc=Start-Process -FilePath $uninstall -ArgumentList @('/S','/currentuser') -Wait -PassThru -WindowStyle Hidden
   if($proc.ExitCode -ne 0 -or (Test-Path -LiteralPath (Join-Path $folder 'DICloak.exe') -PathType Leaf)){
     $summary += @{product=$entry.Name;result='manual-uninstall-required';reason='uninstall-failed'}
     $problems++;continue
   }
   $oldTarget=Join-Path $folder 'DICloak.exe'
   Remove-VerifiedShortcut (Join-Path $desktop ($entry.Shortcut+'.lnk')) $oldTarget
   Remove-VerifiedShortcut (Join-Path $startPrograms ($entry.Shortcut+'\'+$entry.Shortcut+'.lnk')) $oldTarget
   $summary += @{product=$entry.Name;result='old-program-uninstalled'}
 }catch{
   $summary += @{product=$entry.Name;result='manual-uninstall-required';reason='uninstall-error'}
   $problems++
 }
}
try{
 $outDir=Join-Path $env:LOCALAPPDATA 'diloakPRO'
 New-Item -ItemType Directory -Path $outDir -Force|Out-Null
 $removedCount=@($summary | Where-Object {$_.result -eq 'old-program-uninstalled'}).Count
 $report=[ordered]@{
   schema=1
   removedCount=$removedCount
   issues=$problems
   actions=@($summary)
   userDataPreserved=$true
 }
 $json=ConvertTo-Json -InputObject $report -Depth 5
 $outFile=Join-Path $outDir 'install-migration.json'
 [IO.File]::WriteAllText($outFile,$json,[Text.UTF8Encoding]::new($false))
}catch{
  [Console]::Error.WriteLine('MIGRATION_REPORT_WRITE_ERROR='+$_.Exception.GetType().Name+':'+$_.Exception.Message)
  exit 4
}
if($problems -gt 0){exit 2}
exit 0
